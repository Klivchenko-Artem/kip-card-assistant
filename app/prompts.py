def user_message(
    product: ProductInput, empty_specs: list[str] | None = None, thin: bool = False
) -> str:
    payload = json.dumps(product.model_dump(), ensure_ascii=False, indent=2)
    message = f"Подготовь черновик карточки по этим данным:\n\n{payload}"
    if empty_specs:
        listed = ", ".join(empty_specs)
        message += f"\n\nЭти поля пришли пустыми, программа сама покажет их как «{NO_DATA}», в key_specs их не включай: {listed}."
    if thin:
        message += (
            f"\n\nДанных мало. Требование к минимальной длине seo_description в этот раз снято: "
            "напиши столько, сколько позволяют факты, без рассуждений о назначении, удобстве, "
            "совместимости и безопасности. Короткий честный текст лучше длинного."
        )
    return message


def rewrite_message(issues: list[str]) -> str:
    listed = "\n".join(f"- {issue}" for issue in issues)
    return (
        "Черновик не прошел автоматическую проверку:\n"
        f"{listed}\n\n"
        "Исправь только эти замечания и верни весь ответ целиком в том же формате. "
        "Значения, которых нет во входных данных, удали, а не заменяй похожими. "
        "Если текст короткий, раскрой уже имеющиеся факты подробнее, новых не добавляй."
    )
